create table if not exists public.marketplace_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'buyer' check (role in ('buyer','seller','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.marketplace_categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null unique
);

create table if not exists public.marketplace_products (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid references auth.users(id) on delete set null,
  category_id bigint not null references public.marketplace_categories(id),
  title text not null check (length(trim(title)) between 3 and 140),
  description text not null default '',
  image_url text not null default '',
  price_xaf bigint not null check (price_xaf >= 0),
  stock integer not null default 1 check (stock >= 0),
  city text not null default 'Cameroon',
  status text not null default 'pending' check (status in ('pending','active','rejected')),
  is_sample boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.marketplace_products
  add column if not exists is_sample boolean not null default false;

create table if not exists public.marketplace_seller_payment_methods (
  seller_id uuid primary key references auth.users(id) on delete cascade,
  mtn_number text not null default '',
  mtn_account_name text not null default '',
  orange_number text not null default '',
  orange_account_name text not null default '',
  bank_name text not null default '',
  bank_account_name text not null default '',
  bank_account_number text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.marketplace_orders (
  id uuid primary key default gen_random_uuid(),
  tracking_code text not null unique default upper(replace(gen_random_uuid()::text,'-','')),
  buyer_id uuid not null references auth.users(id),
  seller_id uuid not null references auth.users(id),
  product_id uuid not null references public.marketplace_products(id),
  product_title text not null,
  quantity integer not null check (quantity between 1 and 1000),
  unit_price_xaf bigint not null check (unit_price_xaf >= 0),
  total_xaf bigint not null check (total_xaf >= 0),
  buyer_name text not null,
  buyer_email text not null,
  buyer_phone text not null,
  delivery_address text not null,
  payment_method text not null check (payment_method in ('mtn_momo','orange_money','bank_transfer')),
  payment_instructions jsonb not null,
  payment_status text not null default 'pending' check (payment_status in ('pending','received')),
  order_status text not null default 'placed' check (order_status in ('placed','processing','shipped','delivered','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.marketplace_tracking_updates (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.marketplace_orders(id) on delete cascade,
  seller_id uuid not null references auth.users(id),
  status_label text not null check (status_label in ('processing','shipped','in_transit','out_for_delivery','delivered')),
  note text not null default '' check (length(note) <= 500),
  latitude numeric(9,6) check (latitude between -90 and 90),
  longitude numeric(9,6) check (longitude between -180 and 180),
  location_label text not null default '' check (length(location_label) <= 160),
  created_at timestamptz not null default now(),
  check ((latitude is null and longitude is null) or (latitude is not null and longitude is not null))
);

create index if not exists marketplace_products_catalog_idx
  on public.marketplace_products(status, category_id, created_at desc);
create index if not exists marketplace_products_owner_idx
  on public.marketplace_products(owner_id, created_at desc);
create index if not exists marketplace_orders_buyer_idx
  on public.marketplace_orders(buyer_id, created_at desc);
create index if not exists marketplace_orders_seller_idx
  on public.marketplace_orders(seller_id, created_at desc);
create index if not exists marketplace_tracking_order_idx
  on public.marketplace_tracking_updates(order_id, created_at desc);

create or replace function public.create_marketplace_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare requested_role text;
begin
  requested_role := case
    when new.raw_user_meta_data ->> 'role' = 'seller' then 'seller'
    else 'buyer'
  end;
  insert into public.marketplace_profiles(id, display_name, role)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), split_part(new.email, '@', 1)),
    requested_role
  );
  return new;
end;
$$;

drop trigger if exists on_marketplace_auth_user_created on auth.users;
create trigger on_marketplace_auth_user_created
  after insert on auth.users
  for each row execute function public.create_marketplace_profile();

create or replace function public.keep_marketplace_role_private()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.role is distinct from old.role
    and current_user not in ('postgres','service_role','supabase_admin') then
    raise exception 'Marketplace roles can only be changed by an administrator';
  end if;
  return new;
end;
$$;

drop trigger if exists marketplace_profile_role_immutable on public.marketplace_profiles;
create trigger marketplace_profile_role_immutable
  before update of role on public.marketplace_profiles
  for each row execute function public.keep_marketplace_role_private();

create or replace function public.is_marketplace_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.marketplace_profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

revoke all on function public.is_marketplace_admin() from public;
grant execute on function public.is_marketplace_admin() to authenticated;
grant execute on function public.is_marketplace_admin() to anon;

