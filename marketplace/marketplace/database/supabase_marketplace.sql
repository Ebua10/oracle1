  on public.marketplace_seller_payment_methods for all to authenticated
  using (seller_id = (select auth.uid()) or (select public.is_marketplace_admin()))
  with check (
    (seller_id = (select auth.uid()) and exists (
      select 1 from public.marketplace_profiles
