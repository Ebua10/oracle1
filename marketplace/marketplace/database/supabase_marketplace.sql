create or replace function public.create_marketplace_order(
  p_product_id uuid,
  p_quantity integer,
  p_buyer_name text,
  p_buyer_email text,
  p_buyer_phone text,
  p_delivery_address text,
  p_payment_method text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  buyer uuid := (select auth.uid());
  product public.marketplace_products%rowtype;
  seller_payment public.marketplace_seller_payment_methods%rowtype;
  instructions jsonb;
  order_row public.marketplace_orders%rowtype;
begin
  if buyer is null then raise exception 'Sign in before checkout'; end if;
  if p_quantity is null or p_quantity < 1 or p_quantity > 1000 then raise exception 'Quantity must be between 1 and 1000'; end if;
  if length(trim(coalesce(p_buyer_name,''))) not between 2 and 100 then raise exception 'Enter your name'; end if;
  if length(trim(coalesce(p_buyer_email,''))) not between 5 and 254 or p_buyer_email !~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' then raise exception 'Enter a valid email address'; end if;
  if lower(trim(p_buyer_email)) <> lower(coalesce((select auth.jwt() ->> 'email'),'')) then raise exception 'Use the email address on your signed-in buyer account'; end if;
  if length(trim(coalesce(p_buyer_phone,''))) not between 6 and 32 then raise exception 'Enter a valid phone number'; end if;
  if length(trim(coalesce(p_delivery_address,''))) not between 5 and 500 then raise exception 'Enter a delivery address'; end if;
  if p_payment_method is null or p_payment_method not in ('mtn_momo','orange_money','bank_transfer') then raise exception 'Select a supported payment method'; end if;
  if not exists (select 1 from public.marketplace_profiles where id = buyer and role = 'buyer') then raise exception 'A buyer account is required'; end if;

  select * into product
  from public.marketplace_products
  where id = p_product_id and status = 'active'
  for update;
  if not found then raise exception 'Product is no longer available'; end if;
  if product.is_sample or product.owner_id is null or product.owner_id = buyer then raise exception 'This preview listing cannot be purchased'; end if;
  if product.stock < p_quantity then raise exception 'The requested quantity is not available'; end if;

  select * into seller_payment
  from public.marketplace_seller_payment_methods
  where seller_id = product.owner_id;
  if not found then raise exception 'Seller has not configured payment instructions'; end if;

  if p_payment_method = 'mtn_momo' then
    if length(trim(seller_payment.mtn_number)) = 0 then raise exception 'Seller has not configured MTN Mobile Money'; end if;
    instructions := jsonb_build_object('method','MTN Mobile Money','account_name',seller_payment.mtn_account_name,'account_number',seller_payment.mtn_number);
  elsif p_payment_method = 'orange_money' then
    if length(trim(seller_payment.orange_number)) = 0 then raise exception 'Seller has not configured Orange Money'; end if;
    instructions := jsonb_build_object('method','Orange Money','account_name',seller_payment.orange_account_name,'account_number',seller_payment.orange_number);
  else
    if length(trim(seller_payment.bank_name)) = 0 or length(trim(seller_payment.bank_account_number)) = 0 then raise exception 'Seller has not configured bank transfer'; end if;
    instructions := jsonb_build_object('method','Bank transfer','bank_name',seller_payment.bank_name,'account_name',seller_payment.bank_account_name,'account_number',seller_payment.bank_account_number);
  end if;

  insert into public.marketplace_orders(
    buyer_id,seller_id,product_id,product_title,quantity,unit_price_xaf,total_xaf,
    buyer_name,buyer_email,buyer_phone,delivery_address,payment_method,payment_instructions
  ) values (
    buyer,product.owner_id,product.id,product.title,p_quantity,product.price_xaf,product.price_xaf * p_quantity,
    trim(p_buyer_name),lower(trim(p_buyer_email)),trim(p_buyer_phone),trim(p_delivery_address),p_payment_method,instructions
  ) returning * into order_row;

  update public.marketplace_products set stock = stock - p_quantity where id = product.id;

  return jsonb_build_object(
    'id',order_row.id,
    'tracking_code',order_row.tracking_code,
    'product_title',order_row.product_title,
    'quantity',order_row.quantity,
    'unit_price_xaf',order_row.unit_price_xaf,
    'total_xaf',order_row.total_xaf,
    'buyer_email',order_row.buyer_email,
    'payment_method',order_row.payment_method,
    'payment_instructions',order_row.payment_instructions,
    'payment_status',order_row.payment_status,
    'order_status',order_row.order_status
  );
end;
$$;

